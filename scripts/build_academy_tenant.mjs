import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { materializeImmutableAcademyBundle } from './lib/academyReleaseAssets.mjs';
import { validateBuildEnv } from './lib/build-env.mjs';
import { ACADEMY_TENANT_CONTRACT } from '../src/services/academyTenantContract.ts';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const profilePath=path.resolve(repo,process.argv[2]||'config/academy-005jda.public.json');
const outDir=path.resolve(repo,process.argv[3]||'dist/academy-005jda');
const raw=fs.readFileSync(profilePath),profile=JSON.parse(raw);
if(profile.VITE_TENANT_KEY!==ACADEMY_TENANT_CONTRACT.tenantKey)throw new Error('This build profile must bind tenant 005JDA');
const errors=validateBuildEnv(profile);if(errors.length)throw new Error(errors.join('\n'));
const base=new URL(profile.VITE_ACADEMY_BACKEND_BASE);
if(base.protocol!=='https:'||base.pathname.replace(/\/+$/,'')!==ACADEMY_TENANT_CONTRACT.namespace||base.search||base.hash||base.username||base.password)throw new Error('Invalid academy backend URL');
for(const[key,value]of Object.entries(profile))if(!key.startsWith('VITE_')||typeof value!=='string'||/[\r\n]/.test(value))throw new Error('Only single-line public VITE values belong in the profile');
const run=(args)=>{const result=spawnSync(process.execPath,args,{cwd:repo,env:{...process.env,...profile},stdio:'inherit'});if(result.status!==0)process.exit(result.status||1);};
run(['scripts/assert-clean-deploy.mjs']);
run(['node_modules/typescript/bin/tsc','-b']);
run(['node_modules/vite/bin/vite.js','build','--config','vite.config.academy.ts','--mode','dev','--base','./','--outDir',outDir]);
run(['scripts/write-release.mjs',outDir,'release-ffc-academy-dev.json']);
fs.copyFileSync(path.join(repo,'docs/academy-preview/index.html'),path.join(outDir,'index.html'));
for(const file of ['LPD.png','manifest.json'])fs.rmSync(path.join(outDir,file),{force:true});
const manifestPath=path.join(outDir,'release-ffc-academy-dev.json'),manifest=JSON.parse(fs.readFileSync(manifestPath));
const immutable=materializeImmutableAcademyBundle(outDir,manifest.version);
Object.assign(manifest,{academyBundlePath:immutable.path,academyBundleSha256:immutable.sha256,tenantKey:profile.VITE_TENANT_KEY,publicProfileSha256:crypto.createHash('sha256').update(raw).digest('hex')});
fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
run(['scripts/assert-clean-deploy.mjs',path.relative(repo,manifestPath)]);
console.log('Academy 005JDA bundle ready; backend activation is a separate step.');
